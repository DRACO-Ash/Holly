#!/usr/bin/env node
// mutation-battery.mjs :: shows that the contrast check's and the licence plugin's self-tests can
// fail. Not part of the loop: run it after changing either control or its self-test. CI runs it
// after the loop on every push.
// Usage: node scripts/mutation-battery.mjs (after npm ci in frontend/)
//
// Each mutant replaces one exact text in a copy of scripts/contrast-check.mjs or
// frontend/bundled-licences.mjs, removing, loosening or moving one control, and runs the case of
// that control's self-test the mutant names, on the copy: the case must fail, so a mutant that
// some other case catches proves nothing about the control, and the mutated file must still
// parse, so a typo cannot pass for a kill. A mutant whose text is missing, or found twice, fails
// the battery, so a refactor that moves a control says that its proof has stopped measuring. The
// lists the check measures, the properties it holds to the tokens, the words a painting value and
// a flicker's animation may hold, and the alternatives of the patterns it allows a value by are
// written out below too: each must equal the check's own, so an entry added there without a case
// fails the battery, and each entry, taken out alone, is a mutant that must turn red the case
// named for it, or for words and alternatives the one case that uses them all. Each
// self-test must first pass whole on an unmutated copy, every case a mutant names among them. An
// equivalent mutant is one no case may tell from the original: each must leave its whole
// self-test passing, or it is not equivalent and belongs in the table with a case that kills it.
