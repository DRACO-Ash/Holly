// The file with the text replaced, or the reason it cannot be.
const mutate = (file, text, replacement) => {
  const count = pristine[file].split(text).length - 1;
  if (count !== 1) return { problem: `its text is found ${count} times in ${file}, not once` };
  return { source: pristine[file].replace(text, () => replacement) };
};

// A self-test, or one of its cases, run on the copy with the mutated file in place once it is
// known to parse; null when it does not.
const under = (file, source, ...args) => {
  writeFileSync(join(work, file), source);
  try {
    const parses = spawnSync(process.execPath, ['--check', join(work, file)]).status === 0;
    return parses ? run(file, ...args) : null;
  } finally {
    writeFileSync(join(work, file), pristine[file]);
  }
};

let bad = 0;
